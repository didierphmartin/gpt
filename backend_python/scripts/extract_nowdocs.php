<?php
/**
 * Extract every nowdoc (<<<'TAG' ... TAG) of a PHP source file into a Python
 * module of byte-exact string constants.
 *
 * The PHP compilers (LangGraphGenerator, LangGraphRuntime, ...) carry most of
 * the Python they emit as nowdoc literals. Their Python ports must emit the
 * very same bytes, so instead of re-typing those literals the port imports
 * them from a module this script writes. Re-run it after the PHP literal
 * changes:
 *
 *   php backend_python/scripts/extract_nowdocs.php \
 *       backend/src/AgentTeam/Services/LangGraphRuntime.php \
 *       backend_python/app/agent_team/services/compiler_text/lang_graph_runtime.py
 *
 * Constant names: <php function>__<what the literal is assigned to>, where
 * that is the variable name ($base -> base), the array key ('typesafe' =>),
 * the class constant name, or "ret" for a returned / concatenated literal.
 * A repeated name gets _2, _3, ... in source order.
 */
declare(strict_types=1);

if ($argc < 3) {
    fwrite(STDERR, "usage: extract_nowdocs.php <php source> <python module out>\n");
    exit(2);
}
[$_, $src, $out] = $argv;
$tokens = token_get_all(file_get_contents($src));
$n = count($tokens);

$names = [];
$consts = [];
$func = '_class';
$braceDepth = 0;
$funcDepth = null;

$prevSignificant = function (int $i) use ($tokens): array {
    $found = [];
    for ($j = $i - 1; $j >= 0 && count($found) < 3; $j--) {
        $t = $tokens[$j];
        if (is_array($t) && in_array($t[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
            continue;
        }
        $found[] = $t;
    }
    return $found;
};

for ($i = 0; $i < $n; $i++) {
    $t = $tokens[$i];
    if ($t === '{' || (is_array($t) && in_array($t[0], [T_CURLY_OPEN, T_DOLLAR_OPEN_CURLY_BRACES], true))) {
        $braceDepth++;
        continue;
    }
    if ($t === '}') {
        $braceDepth--;
        if ($funcDepth !== null && $braceDepth < $funcDepth) {
            $func = '_class';
            $funcDepth = null;
        }
        continue;
    }
    if (is_array($t) && $t[0] === T_FUNCTION) {
        for ($j = $i + 1; $j < $n; $j++) {
            if (is_array($tokens[$j]) && $tokens[$j][0] === T_STRING) {
                if ($funcDepth === null) {   // closures inside a method keep the method name
                    $func = $tokens[$j][1];
                    $funcDepth = $braceDepth + 1;
                }
                break;
            }
            if ($tokens[$j] === '(') {
                break;   // closure
            }
        }
        continue;
    }
    if (!is_array($t) || $t[0] !== T_START_HEREDOC) {
        continue;
    }
    if (!preg_match("/^<<<\\s*'/", $t[1])) {
        fwrite(STDERR, "interpolating heredoc at line {$t[2]} is not supported\n");
        exit(1);
    }
    $code = $t[1];
    for ($j = $i + 1; $j < $n; $j++) {
        $code .= is_array($tokens[$j]) ? $tokens[$j][1] : $tokens[$j];
        if (is_array($tokens[$j]) && $tokens[$j][0] === T_END_HEREDOC) {
            break;
        }
    }
    $value = eval('return ' . $code . ";\n");
    $prev = $prevSignificant($i);
    $what = 'ret';
    if (($prev[0] ?? null) === '=' && is_array($prev[1] ?? null) && $prev[1][0] === T_VARIABLE) {
        $what = ltrim($prev[1][1], '$');
    } elseif (($prev[0] ?? null) === '=' && is_array($prev[1] ?? null) && $prev[1][0] === T_STRING) {
        $what = $prev[1][1];   // const NAME =
    } elseif (is_array($prev[0] ?? null) && $prev[0][0] === T_DOUBLE_ARROW && is_array($prev[1] ?? null)
        && $prev[1][0] === T_CONSTANT_ENCAPSED_STRING) {
        $what = trim($prev[1][1], "'\"");
    }
    $name = preg_replace('/[^A-Za-z0-9_]/', '_', "{$func}__{$what}");
    $names[$name] = ($names[$name] ?? 0) + 1;
    if ($names[$name] > 1) {
        $name .= '_' . $names[$name];
    }
    $consts[] = [$name, $value, $t[2]];
    $i = $j;
}

/** A Python literal whose value is exactly $s. */
function pyLiteral(string $s): string
{
    foreach (["'''", '"""'] as $q) {
        $c = $q[0];
        if (strpos($s, $q) === false && !str_ends_with($s, $c) && !str_ends_with($s, '\\')
            && strpos($s, "\r") === false && strpos($s, "\\{$c}") === false && strpos($s, "\0") === false) {
            return "r{$q}{$s}{$q}";
        }
    }
    // Fallback: an escaped literal, one source line per text line.
    $parts = [];
    foreach (preg_split('/(?<=\n)/', $s) as $line) {
        if ($line === '') {
            continue;
        }
        $e = strtr($line, ['\\' => '\\\\', "'" => "\\'", "\n" => '\\n', "\r" => '\\r', "\t" => '\\t', "\0" => '\\0']);
        $parts[] = "    '{$e}'";
    }
    return $parts === [] ? "''" : "(\n" . implode("\n", $parts) . "\n)";
}

$rel = preg_replace('#^.*?(backend/src/)#', '$1', realpath($src) ?: $src);
$py = "# GENERATED by backend_python/scripts/extract_nowdocs.php from {$rel} -- do not edit.\n"
    . "# Every constant is one nowdoc of that file, byte for byte (re-run the script when it changes).\n"
    . "# ruff: noqa\n# fmt: off\n";
foreach ($consts as [$name, $value, $line]) {
    $py .= "\n# {$rel}:{$line}\n{$name} = " . pyLiteral($value) . "\n";
}
// A self-check the port's tests run: name -> sha256 of the PHP value.
$py .= "\nSHA256 = {\n";
foreach ($consts as [$name, $value]) {
    $py .= "    '{$name}': '" . hash('sha256', $value) . "',\n";
}
$py .= "}\n";
file_put_contents($out, $py);
fwrite(STDERR, count($consts) . " nowdocs -> {$out}\n");
