"""Port of backend/src/AgentTeam/Services/LangGraphRuntime.php.

The Python runtime blocks the LangGraph compiler owns. Every mode LangGraph emits --
the single file, the modular package's common.py and each self-contained A2A agent
server -- concatenates these same blocks, so a class is written once here and runs
identically everywhere. The blocks are LangGraph's alone: ADK, MAF and NOOA never call
this class, so a change here cannot reach their output.

The text of every block is the PHP nowdoc byte for byte (compiler_text.lang_graph_runtime,
generated by scripts/extract_nowdocs.php); this module holds only the assembly logic.
"""
from __future__ import annotations

import os

from app.agent_team.services.compiler_php import j, str_replace_count
from app.agent_team.services.compiler_text import lang_graph_runtime as T

# frontend/assets/py/code_node_harness.py, the file the editor runs.
CODE_HARNESS_PATH = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', 'frontend', 'assets', 'py',
    'code_node_harness.py'))


class LangGraphRuntime:
    # Python adapter class per decision protocol: the runtime twin of DecisionProtocols' 'adapter'.
    ADAPTER_CLASSES = {'typesafe': 'JevRouter', 'openai': 'OpenAIDecisionRouter'}

    @staticmethod
    def nodeClassesBlock(withPlaybook: bool, withCode: bool = False) -> str:
        """Node, its subclasses, NodeKind and make_node(); PlaybookNode / CodeNode and their
        make_node() arms only when the file carries their runtime."""
        return (T.nodeClassesBlock__base + (T.nodeClassesBlock__playbook if withPlaybook else '')
                + (T.nodeClassesBlock__code if withCode else '')
                + T.nodeClassesBlock__kindHead + '\n' + ('    CODE = "code"\n' if withCode else '')
                + T.nodeClassesBlock__makeHead
                + (T.nodeClassesBlock__playbookArm if withPlaybook else '')
                + (T.nodeClassesBlock__codeArm if withCode else '') + T.nodeClassesBlock__factoryTail)

    @classmethod
    def dispatcherBlock(cls, protocols: list) -> str:
        """DecisionResult, one adapter per decision protocol used, DECISION_ADAPTERS, RouteDecision, Dispatcher."""
        return cls.decisionAdaptersBlock(protocols) + cls._dispatcherClasses()

    @classmethod
    def decisionAdaptersBlock(cls, protocols: list) -> str:
        """DecisionResult, one adapter class per protocol and DECISION_ADAPTERS (standard library only)."""
        return cls._decisionHead() + ''.join(cls._adapterBlock(p) for p in protocols) + cls._adaptersTable(protocols)

    @staticmethod
    def _decisionHead() -> str:
        return ('# Decision-model routing (twin of DecisionProtocols.php / DecisionRouters.php).\n\n\n'
                + T.decisionHead__ret)

    @staticmethod
    def _adapterBlock(protocol: str) -> str:
        match protocol:
            case 'typesafe':
                return T.adapterBlock__typesafe
            case 'openai':
                return T.adapterBlock__openai
            case _:
                raise ValueError(f"no LangGraph adapter for decision protocol '{protocol}'")

    @classmethod
    def _adaptersTable(cls, protocols: list) -> str:
        entries = ['"' + p + '": ' + cls.ADAPTER_CLASSES[p] for p in protocols]
        return ("# Decision protocol -> adapter class (only the protocols this workflow's dispatchers use).\n"
                + 'DECISION_ADAPTERS = {' + ', '.join(entries) + '}\n\n\n')

    @staticmethod
    def _dispatcherClasses() -> str:
        return T.dispatcherClasses__ret

    @staticmethod
    def codeHarnessBlock(fromFile: bool = False) -> str:
        """The code node harness embedded as a module (fromFile: imported from the package's
        code_harness.py), plus the transport its call_tool uses."""
        if fromFile:
            load = 'import code_harness as CODE_HARNESS   # code_harness.py in the package folder\n\n\n'
        else:
            try:
                with open(CODE_HARNESS_PATH, encoding='utf-8', newline='') as f:
                    src = f.read()
            except OSError:
                raise RuntimeError('code node harness not found (frontend/assets/py/code_node_harness.py)')
            load = ('CODE_HARNESS_SOURCE = ' + j(src) + '\n'
                    + 'CODE_HARNESS = types.ModuleType("code_node_harness")\n'
                    + 'exec(CODE_HARNESS_SOURCE, CODE_HARNESS.__dict__)\n\n\n')
        return ('# ==============================================================\n'
                + '# CODE NODE HARNESS -- the same file the workflow editor runs\n'
                + '# ==============================================================\n'
                + load
                + 'def _code_transport(server: str, tool: str, args: dict) -> dict:\n'
                + '    """call_tool\'s transport in a compiled script: the raw MCP result of server.tool(args)."""\n'
                + '    url = MCP_SLUGS.get(server)\n'
                + '    if not url:\n'
                + '        return {"isError": True, "content": [{"type": "text", "text": f"MCP server {server!r} is not in this workflow"}]}\n'
                + '    return MCP.call_tool_raw(url, tool, args)\n')

    @staticmethod
    def runRecordBlock() -> str:
        return T.runRecordBlock__ret

    @staticmethod
    def liveFeedBlock() -> str:
        return T.liveFeedBlock__ret

    @staticmethod
    def consoleBlock() -> str:
        return T.consoleBlock__ret

    @staticmethod
    def runContextBlock() -> str:
        return T.runContextBlock__ret

    @classmethod
    def workflowGraphBlock(cls) -> str:
        return T.workflowGraphBlock__ret.replace('{RUN_CONTEXT}', cls.runContextBlock() + '\n')

    @staticmethod
    def cronBlock() -> str:
        return T.cronBlock__ret

    @staticmethod
    def watchBlock() -> str:
        return T.watchBlock__ret

    @staticmethod
    def listenerBlock() -> str:
        return T.listenerBlock__ret

    @staticmethod
    def outputBlock(packaged: bool = False) -> str:
        """save_output() and print_run_summary(); packaged: outputs/ inside the program's folder."""
        block = T.outputBlock__block
        if not packaged:
            return block
        out, n = str_replace_count([
            'app stores it (~/Documents/synergyAI/outputs/workflow/ by default, overridable via',
            'root = os.environ.get("SYNERGYAI_OUTPUT_ROOT") or os.path.expanduser("~/Documents/synergyAI/outputs")',
        ], [
            'program stores it (<program folder>/outputs/workflow/ by default, overridable via',
            'root = os.environ.get("SYNERGYAI_OUTPUT_ROOT") or os.path.join(PACKAGE_DIR, "outputs")',
        ], block)
        if n != 2:
            raise RuntimeError('outputBlock: the packaged defaults no longer match the block')
        return out

    @staticmethod
    def llmFactoryBlock() -> str:
        return T.llmFactoryBlock__ret

    @staticmethod
    def documentConverterBlock() -> str:
        return T.documentConverterBlock__ret

    @staticmethod
    def mcpClientBlock() -> str:
        return T.mcpClientBlock__ret

    @staticmethod
    def toolCatalogBlock() -> str:
        return T.toolCatalogBlock__ret

    @staticmethod
    def skillRuntimeBlock(packaged: bool = False) -> str:
        """SkillRuntime and SKILLS; packaged: skills/, outputs/ and scratch/ are the package's folders."""
        block = T.skillRuntimeBlock__block
        if not packaged:
            return block
        out, n = str_replace_count([
            'SKILLS_DIR = os.environ.get(\n    "SYNERGYAI_SKILLS_DIR",\n    os.path.join(os.path.expanduser("~"), "Documents", "synergyAI", "skills"),\n)\n',
            'os.path.join(os.path.dirname(SKILLS_DIR), "outputs")',
            'os.path.join(os.path.dirname(SKILLS_DIR), "scratch")',
        ], [
            'SKILLS_DIR = os.environ.get("SYNERGYAI_SKILLS_DIR") or os.path.join(PACKAGE_DIR, "skills")   # the package\'s own skills/\n',
            'os.path.join(PACKAGE_DIR, "outputs")',
            'os.path.join(PACKAGE_DIR, "scratch")',
        ], block)
        if n != 3:
            raise RuntimeError('skillRuntimeBlock: the packaged defaults no longer match the block')
        return out

    @staticmethod
    def runEventsBlock() -> str:
        return T.runEventsBlock__ret

    @staticmethod
    def playbookBlock() -> str:
        return T.playbookBlock__ret
